# rl_engine/environment/signal_program.py

"""
SIGNAL PROGRAM BUILDER — installs an India-style, one-direction-at-a-time,
clockwise rotating traffic light program.

WHY NOT EDIT network.net.xml DIRECTLY?
That file is meant to be generated by netconvert only — we learned that
lesson the hard way in Phase 1. Instead, we ask SUMO at runtime "which
links do you control?" and build our own phase program from that,
direction by direction. This works correctly no matter how many lanes
netconvert created, and never requires touching the XML files again.
"""

import traci

CLOCKWISE_ORDER = ["north", "east", "south", "west"]

# Default mapping for the SINGLE intersection (C)
DEFAULT_INCOMING_EDGES = {
    "north": "N2C",
    "east":  "E2C",
    "south": "S2C",
    "west":  "W2C",
}

YELLOW_DURATION        = 3
DEFAULT_GREEN_DURATION = 30


def _get_link_directions(tls_id, incoming_edges, conn=None):
    conn = conn or traci
    controlled_links = traci.trafficlight.getControlledLinks(tls_id)
    directions = []
    for link_group in controlled_links:
        if not link_group:
            directions.append(None)
            continue
        incoming_lane = link_group[0][0]
        incoming_edge = incoming_lane.split("_")[0]
        direction = next(
            (d for d, e in incoming_edges.items() if e == incoming_edge),
            None
        )
        directions.append(direction)
    return directions


def _build_state_string(link_directions, green_direction=None,
                         yellow_direction=None):
    chars = []
    for d in link_directions:
        if d == green_direction:
            chars.append("G")
        elif d == yellow_direction:
            chars.append("y")
        else:
            chars.append("r")
    return "".join(chars)


def install_clockwise_program(tls_id="C", incoming_edges=None, conn=None):
    """
    Installs India-style one-direction-at-a-time clockwise program.

    Parameters:
        tls_id         - traffic light ID in SUMO
        incoming_edges - dict mapping direction→edge_id for THIS intersection.
                         If None, uses the single-intersection defaults.
                         Pass the correct edges for grid intersections!
    """
    conn = conn or traci
    if incoming_edges is None:
        incoming_edges = DEFAULT_INCOMING_EDGES

    link_directions = _get_link_directions(tls_id, incoming_edges, conn=conn)

    phases = []
    for direction in CLOCKWISE_ORDER:
        green_state = _build_state_string(
            link_directions, green_direction=direction
        )
        phases.append(
            traci.trafficlight.Phase(DEFAULT_GREEN_DURATION, green_state)
        )
        yellow_state = _build_state_string(
            link_directions, yellow_direction=direction
        )
        phases.append(
            traci.trafficlight.Phase(YELLOW_DURATION, yellow_state)
        )

    logic = conn.trafficlight.Logic(
        programID="clockwise_india",
        type=0,
        currentPhaseIndex=0,
        phases=phases,
    )
    conn.trafficlight.setProgramLogic(tls_id, logic)
    conn.trafficlight.setPhase(tls_id, 0)